/// What the Activity reports beside its input, for the root to follow.
#[cfg(all(feature = "android", target_os = "android"))]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ActivityEvent {
    /// The window gained (`true`) or lost the person's focus: what a
    /// read is gated on, as the desktop window's focus is.
    Focus(bool),
    /// The Activity is no longer visible -- the app went to the
    /// background: the snackbar closes, its Undo with it (swipe spec §5).
    Stop,
    /// The Activity is being destroyed: its window goes with it.
    Destroy,
}

/// Make the Activity `app` the views' platform, reporting `event` as the
/// Activity's focus and lifecycle change. Call it from `android_main`,
/// before [`View::new`].
///
/// # Errors
/// The toolkit's, as text: a platform is already set in this process.
#[cfg(all(feature = "android", target_os = "android"))]
pub fn init_android(
    app: AndroidApp,
    event: impl Fn(ActivityEvent) + 'static,
) -> Result<(), String> {
    use slint::android::android_activity::{MainEvent, PollEvent};
    slint::android::init_with_event_listener(app, move |polled| {
        if let PollEvent::Main(main) = polled {
            match main {
                MainEvent::GainedFocus => event(ActivityEvent::Focus(true)),
                MainEvent::LostFocus => event(ActivityEvent::Focus(false)),
                MainEvent::Stop => event(ActivityEvent::Stop),
                MainEvent::Destroy => event(ActivityEvent::Destroy),
                _ => {}
            }
        }
    })
    .map_err(|e| e.to_string())
}

/// End the event loop: [`WindowHandle::run`] returns.
pub fn quit_event_loop() {
    // An event loop already gone has nothing to end.
    let _ = slint::quit_event_loop();
}

/// What the platform lacks for the views to work.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PlatformProblem {
    /// The fontconfig library did not load: the toolkit opens it at run
    /// time, and without it every text renders with no font at all.
    NoFontconfig,
}

/// Check, before any window, that the platform has what the views need.
/// It asks the same loader the toolkit's font stack uses, so the answer
/// is the stack's own: a host without the library would otherwise run
/// with no fonts, silently.
///
/// # Errors
/// The first [`PlatformProblem`] found.
pub fn platform_check() -> Result<(), PlatformProblem> {
    // Android draws with the platform's own fonts and has no fontconfig.
    #[cfg(all(unix, not(target_vendor = "apple"), not(target_os = "android")))]
    if fontconfig_sys::statics::LIB_RESULT.is_err() {
        return Err(PlatformProblem::NoFontconfig);
    }
    Ok(())
}

/// The family the platform names for monospaced text, for code and a
/// message's source. Slint reads a `font-family` as a family NAME, so the
/// generic `monospace` matches no font and code falls back to the
/// proportional default (seen in the rendered window, 2026-10-04); this
/// asks the font stack the renderer itself uses which family that generic
/// is. Empty -- the default font -- when it names none, or without a
/// window.
fn code_font() -> SharedString {
    #[cfg(feature = "desktop")]
    {
        use i_slint_common::sharedfontique::fontique::{
            Collection, CollectionOptions, GenericFamily,
        };
        let mut fonts = Collection::new(CollectionOptions {
            shared: false,
            system_fonts: true,
        });
        let family = fonts.generic_families(GenericFamily::Monospace).next();
        if let Some(name) = family.and_then(|id| fonts.family_name(id)) {
            return name.into();
        }
    }
    SharedString::new()
}

/// How many PRESSES wait for [`View::take_events`] at most. A full queue
/// refuses the NEWEST press and counts it: a refused press does nothing
/// and can be pressed again, where dropping the oldest could drop an edit
/// and keep the send after it (agreed, relay seq 10882). Edits, focus
/// changes, a snackbar's closing and leaving for the list are state, not
/// presses, and are never refused; with them, and a root that drains the
/// queue whenever it takes, the queue holds at most six times this plus
/// nine ([`View::queued_inputs`]). A root that stops between takes breaks
/// that number, not the bound: one more edit can wait per conversation
/// selected meanwhile, so the queue stays finite.
pub const INPUT_CAP: usize = 64;

/// How long a leaving row's space takes to close (swipe spec §5: 150 ms),
/// with a frame to spare before it is dropped.
const LEAVING: Duration = Duration::from_millis(170);

/// How long a committed swipe's row is held slid out waiting for the
/// model to take it away, at most, before it springs back.
const COMMIT_HOLD: Duration = Duration::from_millis(1_500);

