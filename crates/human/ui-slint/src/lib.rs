/// What the callbacks share with the view: the queue, and what was on
/// screen when a press happened, so a press is recorded as what the
/// person saw.
///
/// THE QUEUE'S ORDER IS THE PERSON'S ORDER. No queued input is ever moved
/// relative to another, and nothing a person did is held outside it: an
/// edit or a focus change is never refused, and coalesces only in place,
/// into an entry it can replace without changing what any input between
/// them resolves to. Two flags wait outside it, neither a person's act:
/// a render's "viewed", which the root made, and the pane shown or
/// hidden, which the window reports -- both resolved once the queue has
/// drained, against the window as it is then. Back was a flag once, and
/// whichever take resolved it was wrong for a press on one side of it
/// (review rounds 2 and 3 on #291).
/// Three review rounds on #170 found inputs moved or held aside -- a focus
/// change moved past selections, a refused edit reported out of order and
/// then lost when the conversation changed -- so the edit is now in the
/// queue by construction rather than restored to its place.
#[derive(Default)]
struct Shared {
    inputs: VecDeque<Input>,
    refused: u64,
    conversations: HashMap<i32, ConversationKey>,
    items: HashMap<i32, Pressable>,
    selected: Option<ConversationKey>,
    /// The conversation the open conversation's "Hide conversation" was
    /// last pressed for: focus moves after that hide wherever it was, as
    /// after a swipe from inside the row (swipe spec section 10), since
    /// the screen holding the control goes. Taken by the next outcome.
    hidden_from_header: Option<ConversationKey>,
    /// A render showed a conversation with unread items, or the pane came
    /// back on screen: once the queue has drained, read the conversation
    /// then on screen if the window then has focus (rust-ui-dev F1).
    /// Resolved last, it can only read fewer.
    viewed: bool,
    /// The right-hand pane was shown or hidden since the last take (the
    /// window's `pane-shown`): back to the list, the trust settings
    /// closed to it, or a resize across the narrow width. Shown, it reads
    /// what is on screen once the queue has drained. (Hidden needs no
    /// flag: every take closes a conversation's snackbar while that
    /// conversation is off screen.)
    pane_moved: bool,
    notice: Option<SessionNotice>,
    /// The trusted peers as rendered, by handle.
    trusted: HashMap<i32, TransportIdentity>,
    /// The trust change the confirmation shows, as rendered: what a press
    /// of Confirm names.
    pending_shown: Option<TrustChange>,
    /// The confirmation was closed by its act, not by "Do not change":
    /// where focus goes once it has closed.
    trust_confirmed: bool,
    wake: Option<Rc<dyn Fn()>>,
    /// The rows a swipe can move, as rendered, by their swipe key.
    swipes: HashMap<String, swipe::Swipeable>,
    /// The swipe in progress.
    tracked: Option<swipe::Tracked>,
    /// A committed swipe's row, held slid out until the model answers.
    committed: Option<swipe::Committed>,
    /// The platform's touch values.
    touch: TouchSettings,
    /// The platform's haptic tick, played once as a swipe arms.
    haptic: Option<Rc<dyn Fn()>>,
    /// The model's snackbar as last rendered, drawn or not.
    snack: Option<SnackUp>,
    /// The window, to take a snackbar off screen when an input that closes
    /// it is queued.
    window: slint::Weak<AppWindow>,
}

/// A snackbar, as the queue judges what closes it.
#[derive(Clone)]
struct SnackUp {
    id: u64,
    /// The conversation it is shown in; `None` on the list.
    conversation: Option<ConversationKey>,
}

impl SnackUp {
    fn of(snack: &Snackbar) -> Self {
        Self {
            id: snack.id,
            conversation: snack.conversation.clone(),
        }
    }

    /// Whether `input`, once taken, closes this snackbar: its own closing,
    /// and for a conversation's, each input that leaves it (§5) -- Back, a
    /// pick of another conversation, the trust settings opened in its
    /// place. What [`View::take_events`] resolves each to.
    fn closed_by(&self, input: &Input) -> bool {
        match input {
            Input::SnackClosed(id) => *id == self.id,
            Input::Left | Input::TrustPage(true) => self.conversation.is_some(),
            Input::Select(key) => self.conversation.as_ref().is_some_and(|c| c != key),
            _ => false,
        }
    }
}

impl Shared {
    /// Queue `input`, and return the wake hook for the caller to run once
    /// it has RELEASED its borrow of this state: a hook that takes at
    /// once borrows it again (review F3).
    ///
    /// An input that will close the snackbar takes it off the screen now,
    /// with its Undo: an Undo pressed after it would follow the close in
    /// the queue and find nothing (review 5551078222 on #291;
    /// `no_undo_is_offered_after_picking_another_conversation_and_coming_back`,
    /// `a_timed_out_snackbar_leaves_the_screen_at_once`). A refused press
    /// closes nothing, so it hides nothing
    /// (`a_refused_pick_leaves_the_undo_on_screen`).
    #[must_use]
    fn push(&mut self, input: Input) -> Option<Rc<dyn Fn()>> {
        let closes = self.snack.as_ref().is_some_and(|s| s.closed_by(&input));
        let refused = self.refused;
        let wake = self.queue(input);
        if closes
            && self.refused == refused
            && let Some(window) = self.window.upgrade()
        {
            window.set_snack_shown(false);
        }
        wake
    }

    /// Whether a queued input will close `snack`: a render then leaves it
    /// off screen
    /// (`no_undo_is_offered_after_picking_another_conversation_and_coming_back`).
    fn closing(&self, snack: &SnackUp) -> bool {
        self.inputs.iter().any(|i| snack.closed_by(i))
    }

    /// Queue `input` by the rules below, or refuse it at the cap.
    #[must_use]
    fn queue(&mut self, input: Input) -> Option<Rc<dyn Fn()>> {
        // An edit is the composer's STATE: refusing it loses what the
        // person typed (review R2-1), so it is never refused. It replaces a
        // queued edit for the same conversation only while no later input
        // for that conversation follows it -- folding it past a send would
        // send text typed after the press (agreed, relay seq 10885) --
        // otherwise it is appended. So at most one edit waits between any
        // two presses for its conversation.
        if let Input::Draft(key, text) = &input {
            let last_for_key = self.inputs.iter_mut().rev().find(|i| match i {
                Input::Draft(k, _) | Input::Send(k) | Input::Select(k) => k == key,
                _ => false,
            });
            if let Some(Input::Draft(_, queued)) = last_for_key {
                queued.clone_from(text);
            } else {
                self.inputs.push_back(input);
            }
            return self.wake.clone();
        }
        // The trust settings' PeerId field is state as the composer is:
        // never refused, and it replaces a queued edit of the field only
        // while no later trust input follows it, so a proposal reads what
        // was typed before it.
        if let Input::Trust(TrustInput::EntryChanged(text)) = &input {
            let last_trust = self
                .inputs
                .iter_mut()
                .rev()
                .find(|i| matches!(i, Input::Trust(_) | Input::TrustPage(_)));
            if let Some(Input::Trust(TrustInput::EntryChanged(queued))) = last_trust {
                queued.clone_from(text);
            } else {
                self.inputs.push_back(input);
            }
            return self.wake.clone();
        }
        // A focus change is STATE, not a press: refusing it would leave the
        // view believing it still had focus, and a later selection would
        // read while unfocused (review F2). So it is never refused. It
        // replaces a queued focus change only when that is the LAST input
        // -- in place, so nothing moves (rust-ui-dev R1, review N2) -- which
        // leaves at most one between any two other inputs.
        // A snackbar closing is STATE too: refused, an Undo would stay
        // offered after its snackbar had gone, and leaving the conversation
        // closes it. So neither is refused, and each coalesces instead: one
        // closing per snackbar, one Left until a selection or the trust
        // settings follow it.
        if let Input::SnackClosed(id) = input {
            if !self.inputs.contains(&Input::SnackClosed(id)) {
                self.inputs.push_back(input);
            }
            return self.wake.clone();
        }
        if let Input::Left = input {
            let waiting = self
                .inputs
                .iter()
                .rev()
                .take_while(|i| !matches!(i, Input::Select(_) | Input::TrustPage(_)))
                .any(|i| *i == Input::Left);
            if !waiting {
                self.inputs.push_back(input);
            }
            return self.wake.clone();
        }
        if let Input::Focus(_) = input {
            match self.inputs.back_mut() {
                Some(last @ Input::Focus(_)) => *last = input,
                _ => self.inputs.push_back(input),
            }
            return self.wake.clone();
        }
        let presses = self
            .inputs
            .iter()
            .filter(|i| {
                !matches!(
                    i,
                    Input::Focus(_)
                        | Input::Draft(..)
                        | Input::Trust(TrustInput::EntryChanged(_))
                        | Input::SnackClosed(_)
                        | Input::Left
                )
            })
            .count();
        if presses >= INPUT_CAP {
            self.refused += 1;
            return None;
        }
        self.inputs.push_back(input);
        self.wake.clone()
    }
}

/// The trust settings' callbacks: each becomes an input, taken by
/// [`View::take_events`] as the others are.
fn wire_trust(window: &AppWindow, shared: &Rc<RefCell<Shared>>) {
    let s = Rc::clone(shared);
    window.on_trust_entry_edited(move |text| {
        enqueue(&s, Input::Trust(TrustInput::EntryChanged(text.to_string())));
    });
    let s = Rc::clone(shared);
    window.on_trust_add(move || enqueue(&s, Input::Trust(TrustInput::ProposeAllow)));
    let s = Rc::clone(shared);
    window.on_trust_remove(move |handle| {
        let peer = s.borrow().trusted.get(&handle).cloned();
        if let Some(peer) = peer {
            enqueue(&s, Input::Trust(TrustInput::ProposeRevoke(peer)));
        }
    });
    let s = Rc::clone(shared);
    window.on_trust_confirm(move || {
        let shown = s.borrow().pending_shown.clone();
        if let Some(change) = shown {
            s.borrow_mut().trust_confirmed = true;
            enqueue(&s, Input::Trust(TrustInput::Confirm(change)));
        }
    });
    let s = Rc::clone(shared);
    window.on_trust_cancel(move || enqueue(&s, Input::Trust(TrustInput::Cancel)));
}

/// Queue `input` from a window callback, and wake the root after the
/// borrow is released. The root's own calls queue without waking: the
/// root is in control already, and may hold the view borrowed (review N4).
fn enqueue(shared: &RefCell<Shared>, input: Input) {
    let wake = shared.borrow_mut().push(input);
    if let Some(wake) = wake {
        wake();
    }
}

/// Set a flag held outside the queue, and wake the root after the borrow
/// is released, as [`enqueue`] does.
fn flag(shared: &RefCell<Shared>, set: impl FnOnce(&mut Shared)) {
    let wake = {
        let mut shared = shared.borrow_mut();
        set(&mut shared);
        shared.wake.clone()
    };
    if let Some(wake) = wake {
        wake();
    }
}

/// Stable small handles for keys, so a Slint row names its key without
/// the key's own representation crossing into the toolkit.
struct Handles<K> {
    by_key: BTreeMap<K, i32>,
    next: i32,
}

impl<K: Ord + Clone> Handles<K> {
    const fn new() -> Self {
        Self {
            by_key: BTreeMap::new(),
            next: 0,
        }
    }

    fn of(&mut self, key: &K) -> i32 {
        if let Some(handle) = self.by_key.get(key) {
            return *handle;
        }
        let handle = self.next;
        self.next = self.next.wrapping_add(1);
        self.by_key.insert(key.clone(), handle);
        handle
    }

    fn retain(&mut self, live: &[K]) {
        self.by_key.retain(|k, _| live.contains(k));
    }

    /// The key `handle` stands for, while it is drawn.
    fn key_of(&self, handle: i32) -> Option<&K> {
        self.by_key
            .iter()
            .find(|(_, h)| **h == handle)
            .map(|(k, _)| k)
    }
}

